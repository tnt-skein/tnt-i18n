--- Правила множественного числа: сколько у языка форм слова при числе
--- и какая из них нужна числу.
---
--- Правило — таблица `{ forms = n, form = функция }`: функция берёт число
--- и отдаёт номер формы от единицы до `forms`. Строка со множественным
--- числом — список форм в том же порядке, и число форм в ней сверяется
--- с правилом при сборке переводов, а не на первом запросе.
---
--- Встроены два правила. Русское — из `tnt-str` (`plural_form`): одна
--- реализация на оба пакета, и одиннадцать–четырнадцать, дробные
--- и отрицательные числа считаются одинаково и в строке, и в переводе.
--- Украинский и белорусский согласуют слово с числом по тому же правилу
--- и берут его же. Английское — две формы: единица и всё остальное.
--- Прочим языкам правило задают настройкой `plurals`: угадывать его
--- по похожему языку значило бы написать «1,5 livres» там, где нужно
--- «1,5 livre».

local str = require('tnt.str')

local Module = {}

---@class TntI18nRule
---@field forms integer Сколько у языка форм слова при числе
---@field form fun(count: number): integer Номер формы для числа

--- Три формы: «узел», «узла», «узлов».
---@type TntI18nRule
local EAST_SLAVIC = { forms = 3, form = str.plural_form }

--- Две формы: «node» при единице, «nodes» при прочих, в том числе при нуле
--- и дробях. Знак числа форму не меняет: «-1 degree».
---@type TntI18nRule
local ONE_OTHER = {
    forms = 2,
    form = function(count)
        return math.abs(count) == 1 and 1 or 2
    end,
}

--- Встроенные правила по языку.
---@type table<string, TntI18nRule>
Module.BUILTIN = {
    ru = EAST_SLAVIC,
    uk = EAST_SLAVIC,
    be = EAST_SLAVIC,
    en = ONE_OTHER,
}

--- Сколько форм бывает у правила. Больше шести нет ни у одного языка:
--- столько у арабского, и число больше — почти наверняка опечатка.
Module.MAX_FORMS = 6

return Module
